class Product {
  final int id;
  final String name;
  final int price;
  final double rating;
  final int reviews;
  final String category;
  final String brand;
  final String supplier;

  const Product({
    required this.id,
    required this.name,
    required this.price,
    required this.rating,
    required this.reviews,
    required this.category,
    required this.brand,
    required this.supplier,
  });
}
